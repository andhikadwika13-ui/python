pertama = int(input("Angka pertama:"))
kedua = int(input("Angka kedua:"))

tambah = pertama + kedua
kurang = pertama - kedua
kali = pertama * kedua
bagi = pertama / kedua

print("Hasil penjumlahan:", tambah)
print("Hasil pengurangan:",kurang)
print("Hasil perkalian:",kali)
print("Hasil pembagian:",bagi)
print("hasil sisa bagi:" , pertama % kedua)